export const ES: Record<string, string> = { ...SHARED_ES, ...NATIVE_EXTRA };

// Mirrors ui-catalog-es.ts's patterns list, plus native-specific dynamic
// phrases (counts, plurals) this app renders that the shared list doesn't
// cover.
const PATTERNS: Array<[RegExp, (...groups: string[]) => string]> = [
  [/^Step (\d+) of (\d+)$/, (step, total) => `Paso ${step} de ${total}`],
  [/^(\d+) done$/, (count) => `${count} completados`],
  [/^(\d+) min ETA$/, (count) => `${count} min de llegada`],
  [/^ETA (\d+)m$/, (count) => `Llegada ${count} min`],
  [/^Estimated arrival (.+) minutes\.$/, (range) => `Llegada estimada: ${range} minutos.`],
  [/^Fulfilled by (.+)$/, (provider) => `Atendido por ${provider}`],
  [/^Page (\d+) of (\d+)$/, (page, total) => `Página ${page} de ${total}`],
  [/^Selected \((\d+)\)$/, (count) => `Seleccionado (${count})`],
  [/^(\d+) uploaded for this request\.$/, (count) => `${count} foto(s) subida(s) para esta solicitud.`],
  [/^- (.+) rating$/, (rating) => `- ${rating} de calificación`],
  [/^(\d+) minutes? without an assigned technician$/, (count) => `${count} minutos sin técnico asignado`],
  [/^Technician is (online|offline)$/, (value) => `El técnico está ${value === "online" ? "en línea" : "desconectado"}`],
  // Native-specific: "3 more offers waiting", "1 more offer waiting"
  [/^(\d+) more offers? waiting$/, (count) => `${count} oferta${count === "1" ? "" : "s"} más en espera`],
  // Native-specific: "2 invites", "1 invite"
  [/^(\d+) invites?$/, (count) => `${count} invitación${count === "1" ? "" : "es"}`],
  // Native-specific: "Job {id} · " prefix used before a truncated job id
  [/^Job ([a-f0-9]+)$/i, (id) => `Trabajo ${id}`],
  // Native-specific: fallback company chip label "Company {id}"
  [/^Company ([a-f0-9]+)$/i, (id) => `Empresa ${id}`],
  // Native-specific: fallback organization name "Organization {id}"
  [/^Organization ([a-f0-9]+)$/i, (id) => `Organización ${id}`],
  // Native-specific: readiness bar's "Updated Xm ago. A fresher fix..." detail line
  [/^Updated (.+) ago\. A fresher fix helps match nearby work precisely\.$/, (age) => `Actualizado hace ${age}. Un ajuste más reciente ayuda a encontrar trabajo cercano con precisión.`],
  // Native-specific: closeout line validation errors (closeoutLineError in RootApp.tsx)
  [/^Item (\d+): add a customer receipt description\.$/, (index) => `Artículo ${index}: agrega una descripción para el recibo del cliente.`],
  [/^(.+): quantity must be greater than zero\.$/, (label) => `${translateUiText(label)}: la cantidad debe ser mayor que cero.`],
  [/^(.+): enter an amount\.$/, (label) => `${translateUiText(label)}: ingresa un monto.`],
  [/^(.+): choose who provided it\.$/, (label) => `${translateUiText(label)}: elige quién lo proporcionó.`]
];

export function translateUiText(value: string): string {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  const exact = ES[core];
  if (exact) return `${leading}${exact}${trailing}`;
  for (const [pattern, render] of PATTERNS) {
    const match = core.match(pattern);
    if (match) return `${leading}${render(...match.slice(1))}${trailing}`;
  }
  if (core.includes(" · ")) {
    return `${leading}${core.split(" · ").map((part) => translateUiText(part).trim()).join(" · ")}${trailing}`;
  }
  return value;
}
